//! Chunk planning, HLS playlist assembly, and segment duration accounting.
//!
//! Mirrors `app/services/chunk_transcode_service.py` to maintain exact segment index stride,
//! discontinuity mapping, and master playlist consistency.

use crate::services::hls_service::HlsService;
use std::collections::{HashMap, HashSet};
use std::fs;
use std::io::Write;
use std::path::Path;

pub const DEFAULT_CHUNK_DURATION: f64 = 60.0;
pub const SEGMENT_TARGET_DURATION: f64 = 4.0;
pub const SEGMENTS_PER_CHUNK_STRIDE: usize = 32;
pub const MIN_PLANNABLE_CHUNK_SECONDS: f64 = 1e-3;
pub const MIN_CHUNK_YIELD_RATIO: f64 = 0.5;
pub const MIN_COVERAGE_RATIO: f64 = 0.98;
pub const HLS_LAYOUT_MARKER: &str = ".seg_layout";
pub const HLS_LAYOUT_STRIDE: &str = "stride32";

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, PartialEq)]
pub struct TranscodeChunk {
    pub chunk_id: usize,
    pub start_time: f64,
    pub duration: f64,
    pub start_seg: usize,
    pub expected_segs: usize,
}

pub struct ChunkTranscodeService;

impl ChunkTranscodeService {
    /// Divide media duration into contiguous chunk specifications.
    ///
    /// Monotonically strided segment indices (`start_seg = chunk_id * 32`) ensure chunks
    /// never overwrite each other's segments regardless of encoder GOP or keyframe placements.
    /// A final window shorter than `MIN_PLANNABLE_CHUNK_SECONDS` is dropped.
    pub fn plan_chunks(total_duration: f64, chunk_duration: f64) -> Vec<TranscodeChunk> {
        if total_duration <= 0.0 {
            return Vec::new();
        }

        let chunk_dur = if chunk_duration <= 0.0 {
            DEFAULT_CHUNK_DURATION
        } else {
            chunk_duration
        };

        let mut chunks = Vec::new();
        let mut chunk_id = 0;
        let mut current_time = 0.0;

        while current_time < total_duration {
            let dur = (total_duration - current_time).min(chunk_dur);
            if dur < MIN_PLANNABLE_CHUNK_SECONDS {
                break;
            }

            let start_seg = chunk_id * SEGMENTS_PER_CHUNK_STRIDE;
            let expected_segs = ((dur / SEGMENT_TARGET_DURATION).round() as usize).max(1);

            chunks.push(TranscodeChunk {
                chunk_id,
                start_time: current_time,
                duration: dur,
                start_seg,
                expected_segs,
            });

            chunk_id += 1;
            current_time += dur;
        }

        chunks
    }

    /// Parse real segment durations from chunk playlist files generated by FFmpeg.
    pub fn parse_chunk_segment_durations(
        hls_dir: &Path,
        chunk_id: Option<usize>,
    ) -> HashMap<String, f64> {
        let mut durations = HashMap::new();
        let read_dir = match fs::read_dir(hls_dir) {
            Ok(rd) => rd,
            Err(_) => return durations,
        };

        for entry in read_dir.flatten() {
            let file_name = entry.file_name().to_string_lossy().to_string();
            let matches_pattern = match chunk_id {
                Some(id) => file_name == format!("chunk_{}.m3u8", id),
                None => file_name.starts_with("chunk_") && file_name.ends_with(".m3u8"),
            };

            if matches_pattern {
                if let Ok(text) = fs::read_to_string(entry.path()) {
                    let mut current_dur: Option<f64> = None;
                    for line in text.lines() {
                        let trimmed = line.trim();
                        if let Some(rest) = trimmed.strip_prefix("#EXTINF:") {
                            let dur_str = rest.split(',').next().unwrap_or("").trim();
                            if let Ok(d) = dur_str.parse::<f64>() {
                                current_dur = Some(d);
                            }
                        } else if trimmed.ends_with(".ts") {
                            if let Some(dur) = current_dur.take() {
                                durations.insert(trimmed.to_string(), dur);
                            }
                        }
                    }
                }
            }
        }

        durations
    }

    /// Verify a chunk that exited 0 actually produced usable video.
    pub fn chunk_output_ok(hls_dir: &Path, chunk: &TranscodeChunk) -> bool {
        let chunk_pl = hls_dir.join(format!("chunk_{}.m3u8", chunk.chunk_id));
        if !chunk_pl.is_file() {
            return false;
        }

        let text = match fs::read_to_string(&chunk_pl) {
            Ok(t) => t,
            Err(_) => return false,
        };

        let mut durations = Vec::new();
        let mut seg_names = Vec::new();

        let mut current_dur: Option<f64> = None;
        for line in text.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix("#EXTINF:") {
                let dur_str = rest.split(',').next().unwrap_or("").trim();
                if let Ok(d) = dur_str.parse::<f64>() {
                    current_dur = Some(d);
                }
            } else if trimmed.ends_with(".ts") {
                if let Some(dur) = current_dur.take() {
                    durations.push(dur);
                    seg_names.push(trimmed.to_string());
                }
            }
        }

        if durations.is_empty() {
            return false;
        }

        let produced: f64 = durations.iter().sum();
        let expected = chunk.duration;
        if expected <= 0.0 {
            return produced > 0.0;
        }
        if expected < MIN_PLANNABLE_CHUNK_SECONDS {
            return true;
        }

        // A chunk must stay inside its planned segment range (chunk.start_seg .. chunk.start_seg + 32).
        let start_seg = chunk.start_seg;
        for name in &seg_names {
            if let Some(num_str) = name.strip_prefix("segment_").and_then(|s| s.strip_suffix(".ts")) {
                if let Ok(num) = num_str.parse::<usize>() {
                    if num >= start_seg + SEGMENTS_PER_CHUNK_STRIDE {
                        return false;
                    }
                }
            }
        }

        let planned_segs = chunk.expected_segs;
        if seg_names.len() > planned_segs * 2 {
            return false;
        }

        produced >= expected * MIN_CHUNK_YIELD_RATIO
    }

    /// Reconstruct master `playlist.m3u8` from contiguous segment files on disk with RFC 8216 discontinuities.
    pub fn update_master_playlist(
        hls_dir: &Path,
        playlist_path: &Path,
        total_duration: f64,
        is_complete: bool,
    ) -> std::io::Result<f64> {
        let mut disk_segs = Vec::new();
        if let Ok(rd) = fs::read_dir(hls_dir) {
            for entry in rd.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if name.starts_with("segment_") && name.ends_with(".ts") {
                    if let Ok(m) = entry.metadata() {
                        if m.len() > 0 {
                            disk_segs.push(name);
                        }
                    }
                }
            }
        }
        disk_segs.sort();

        if disk_segs.is_empty() {
            return Ok(0.0);
        }

        let mut lines = vec![
            "#EXTM3U".to_string(),
            "#EXT-X-VERSION:3".to_string(),
            format!("#EXT-X-TARGETDURATION:{}", SEGMENT_TARGET_DURATION as u64),
            "#EXT-X-MEDIA-SEQUENCE:0".to_string(),
            "#EXT-X-INDEPENDENT-SEGMENTS".to_string(),
            "#EXT-X-START:TIME-OFFSET=0".to_string(),
        ];

        if !is_complete {
            lines.push("#EXT-X-PLAYLIST-TYPE:EVENT".to_string());
        }

        // Determine chunk boundary segments for #EXT-X-DISCONTINUITY tags
        let mut chunk_start_segs = HashSet::new();
        if total_duration > 0.0 {
            for c in Self::plan_chunks(total_duration, DEFAULT_CHUNK_DURATION) {
                if c.chunk_id > 0 {
                    chunk_start_segs.insert(c.start_seg);
                }
            }
        }

        let durations_map = Self::parse_chunk_segment_durations(hls_dir, None);
        let mut total_sec = 0.0;

        for seg_name in disk_segs {
            let dur = *durations_map.get(&seg_name).unwrap_or(&SEGMENT_TARGET_DURATION);
            if let Some(num_str) = seg_name.strip_prefix("segment_").and_then(|s| s.strip_suffix(".ts")) {
                if let Ok(seg_idx) = num_str.parse::<usize>() {
                    if chunk_start_segs.contains(&seg_idx) {
                        lines.push("#EXT-X-DISCONTINUITY".to_string());
                    }
                }
            }
            lines.push(format!("#EXTINF:{:.6},", dur));
            lines.push(seg_name);
            total_sec += dur;
        }

        if is_complete {
            lines.push("#EXT-X-ENDLIST".to_string());
        }

        let raw_text = lines.join("\n") + "\n";
        let healed_text = HlsService::honest_target_duration(&raw_text);

        // Atomic write via temporary file
        let tmp_path = hls_dir.join(format!("playlist_{}.tmp", std::process::id()));
        {
            let mut f = fs::File::create(&tmp_path)?;
            f.write_all(healed_text.as_bytes())?;
            f.flush()?;
        }
        let _ = fs::rename(&tmp_path, playlist_path);

        // Backup playlist
        let bak_path = hls_dir.join("playlist.m3u8.bak");
        let _ = fs::write(&bak_path, &healed_text);

        // Write layout marker
        let marker = hls_dir.join(HLS_LAYOUT_MARKER);
        let _ = fs::write(&marker, HLS_LAYOUT_STRIDE);

        Ok(total_sec)
    }

    /// Write human-readable progress telemetry into `hls.progress`.
    pub fn write_progress_file(
        hls_dir: &Path,
        total_sec: f64,
        speed: f64,
        is_complete: bool,
    ) -> std::io::Result<()> {
        let content = format!(
            "out_time_us={}\nout_time_ms={}\nspeed={:.2}x\nprogress={}\n",
            (total_sec * 1_000_000.0) as i64,
            (total_sec * 1_000_000.0) as i64,
            speed,
            if is_complete { "end" } else { "continue" }
        );
        let progress_file = hls_dir.join("hls.progress");
        fs::write(progress_file, content)
    }
}
